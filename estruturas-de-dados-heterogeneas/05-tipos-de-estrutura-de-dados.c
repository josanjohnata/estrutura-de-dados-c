// Tipos de estrutura de dados

// As estruturas de dados são fundamentais para a organização e manipulação eficiente de informações em 
// um programa de computador. Elas podem ser homogêneas, com elementos do mesmo tipo, como vetores e 
// matrizes, ou heterogêneas, com elementos de tipos diferentes, como registros. Tipos de dados básicos 
// incluem inteiro, real, lógico e texto.


// Estruturas como listas, filas, pilhas, árvores e grafos são utilizadas para diferentes propósitos, 
// desde armazenamento sequencial até representação de relações complexas. A escolha adequada da estrutura 
// de dados é fundamental para a eficiência dos algoritmos que manipulam esses dados.
